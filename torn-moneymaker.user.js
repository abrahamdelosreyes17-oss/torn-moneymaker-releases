    /*
     * Thin wrappers over the Torn endpoints this tool uses. Every one of these
     * works with a Public access key - that is the point.
     */

    /** Torn's access levels, lowest first. Public is all this tool needs. */
    const ACCESS_PUBLIC = 1;

    const ACCESS_LEVEL_NAMES = {
        1: 'Public',
        2: 'Minimal',
        3: 'Limited',
        4: 'Full',
    };

    /** The full item database. Public key. */
    async function fetchItems(client) {
        const data = await client.get('torn', { selections: 'items' });

        if (!data || !data.items) {
            throw new Error('Torn API returned no item database.');
        }

        return data.items;
    }

    /**
     * City shop inventories, used to build the NPC-sellable allowlist.
     *
     * The selection is `cityshops` and the response key is `cityshops`. An
     * earlier version of this file asked for `shops` and read `data.shops`, which
     * meant the call silently produced nothing, every item came back unverified,
     * and the panel reported "no opportunities" on a page full of them.
     *
     * `shops` is still accepted as a fallback in case the payload is ever served
     * under that key, but a response with neither throws rather than degrading
     * quietly.
     */
    async function fetchShops(client) {
        const data = await client.get('torn', { selections: 'cityshops' });

        const shops = data && (data.cityshops || data.shops);

        if (!shops) {
            throw new Error(
                'Torn API returned no city shop data (expected "cityshops").',
            );
        }

        return shops;
    }

    /**
     * What the current key can actually do.
     *
     * Used only to warn the user when they have pasted in a key with more access
     * than this tool needs. Written so that an unexpected payload shape means
     * "cannot tell" rather than a false alarm or a crash.
     *
     * @returns {{level: number|null, name: string|null}}
     */
    async function fetchKeyAccess(client) {
        try {
            const data = await client.get('key', { selections: 'info' });

            const level = Number(data && data.access_level);
            const name =
                (data && data.access_type) ||
                ACCESS_LEVEL_NAMES[level] ||
                null;

            return {
                level: Number.isFinite(level) ? level : null,
                name,
            };
        } catch {
            // The check is advisory. If it fails, say nothing rather than
            // blocking a key that is probably fine.
            return { level: null, name: null };
        }
    }

    /**
     * Item Market listings for one item: GET /v2/market/{id}/itemmarket.
     *
     * Public key. "Globally cached selection" - Torn serves everyone the same
     * snapshot and refreshes it no faster than `cache_delay` seconds (30 in every
     * observed response), so asking again before cache_timestamp + cache_delay
     * returns the same rows and only spends quota. The caller uses `nextAt` to
     * avoid that.
     *
     * The response names no seller and no listing id: a row is a price and an
     * amount. So an Item Market hit links to the item, never to a seller.
     *
     * @returns {Promise<{listings: Array<{price: number, amount: number}>,
     *   averagePrice: number|null, cacheTimestamp: number|null, nextAt: number,
     *   total: number}>} cacheTimestamp and nextAt in ms
     */
    async function fetchItemMarket(
        client,
        itemId,
        { limit = 20, offset = 0, now = Date.now() } = {},
    ) {
        const data = await client.get(
            'v2/market/' + encodeURIComponent(String(itemId)) + '/itemmarket',
            { limit, offset },
        );

        const market = (data && data.itemmarket) || {};
        const raw = Array.isArray(market.listings) ? market.listings : [];

        const cacheTs = Number(market.cache_timestamp);
        const cacheDelay = Number(market.cache_delay);
        const cacheTimestamp = Number.isFinite(cacheTs) && cacheTs > 0
            ? cacheTs * 1000
            : null;
        const delayMs = (Number.isFinite(cacheDelay) && cacheDelay > 0
            ? cacheDelay
            : 30) * 1000;

        const average = Number(market.item && market.item.average_price);

        return {
            listings: raw
                .map((l) => ({
                    price: Number(l && l.price) || 0,
                    amount: Number(l && (l.amount ?? l.quantity)) || 0,
                }))
                .filter((l) => l.price > 0 && l.amount > 0),
            averagePrice: Number.isFinite(average) && average > 0 ? average : null,
            cacheTimestamp,
            nextAt: (cacheTimestamp || now) + delayMs,
            total: Number(data && data._metadata && data._metadata.total) || raw.length,
        };
    }

    /* ===== src/sources/route.js ===== */
    /*
     * Which Torn page are we on? Pure string work, so it is testable.
     *
     * V1 ran both scanners on every page under `@match .../*`, which is why it
     * lit up on the Items page and in city shops. Here exactly one scanner runs,
     * and on an unrecognised page nothing runs at all.
     */

    const PAGE_BAZAAR = 'bazaar';
    const PAGE_ITEM_MARKET = 'itemmarket';
    const PAGE_NONE = null;

    /**
     * @param {string} href - normally location.href
     * @returns {'bazaar'|'itemmarket'|null}
     */
    function detectPage(href) {
        if (typeof href !== 'string' || !href) return PAGE_NONE;

        const url = href.toLowerCase();

        // Item Market 2.0 lives behind page.php?sid=ItemMarket; imarket.php is
        // the older path and still redirects for some users.
        if (url.includes('sid=itemmarket') || url.includes('/imarket.php')) {
            return PAGE_ITEM_MARKET;
        }

        // Own bazaar and other players' bazaars, new path and legacy query form.
        if (url.includes('/bazaar.php') || url.includes('page=bazaar')) {
            return PAGE_BAZAAR;
        }

        return PAGE_NONE;
    }

    /**
     * Deep link to an item's Item Market page.
     *
     * Used by the panel's navigate button. One click, one navigation - the script
     * never buys anything and never chains a second request off the same click.
     */
    function itemMarketUrl(itemId, itemName) {
        const params = new URLSearchParams({
            itemID: String(itemId),
            itemName: String(itemName || ''),
        });

        return (
            'https://www.torn.com/page.php?sid=ItemMarket#/market/view=search&' +
            params.toString()
        );
    }

    function queryOf(href) {
        try {
            return new URL(href).searchParams;
        } catch {
            return new URLSearchParams();
        }
    }

    /**
     * Whose bazaar is this? `bazaar.php?userId=123`. Null for your own bazaar
     * (no userId) or anything unparseable - a sighting with no seller is simply
     * remembered without one.
     */
    function bazaarOwnerId(href) {
        if (detectPage(href) !== PAGE_BAZAAR) return null;

        const id = queryOf(href).get('userId') || queryOf(href).get('userid');
        return id && /^\d+$/.test(id) ? id : null;
    }

    /**
     * The listing a feed link asked us to point at: `ttItem` / `ttPrice`, which
     * bazaarUrl() in core/feed.js writes. Highlighting it is reading and marking
     * the page the user opened, which is allowed; nothing is clicked or filled.
     */
    function bazaarTarget(href) {
        if (detectPage(href) !== PAGE_BAZAAR) return null;

        const q = queryOf(href);
        const itemId = q.get('ttItem');
        const price = Number(q.get('ttPrice'));

        if (!itemId || !/^\d+$/.test(itemId)) return null;

        return {
            itemId,
            price: Number.isFinite(price) && price > 0 ? price : null,
        };
    }

    /* ===== src/sources/dom/detect.js ===== */
    /*
     * Finding the listing cards on the page.
     *
     * This is the part that has to work, so it uses two strategies and prefers
     * whichever actually finds cards:
     *
     *   1. Image-anchored. Every listing carries an item image whose path holds
     *      the item id (/images/items/206/large.png). Starting there and climbing
     *      to the card is cheap and precise.
     *
     *   2. Content-shaped. Walk the document for elements whose text contains a
     *      price AND "in stock", that are visible and card-sized, then climb to
     *      the smallest ancestor that looks like a whole card (price + stock +
     *      image + plausible dimensions).
     *
     * Strategy 2 is deliberately the same approach as the script that is known to
     * work on live Torn pages. It is slower, so it runs only when strategy 1
     * finds nothing - which keeps the fast path fast without betting the whole
     * feature on it.
     */

    const ITEM_IMAGE_SELECTOR =
        'img[src*="/images/items/"], img[srcset*="/images/items/"]';

    const ITEM_IMAGE_ID_RE = /\/images\/items\/(\d+)\//;

    /** Known card containers, tightest first. */
    const CARD_SELECTOR = [
        '[class*="itemTile"]',
        '[data-testid="item-description"]',
        '[class*="itemDescription"]',
        '[class*="sellerRow"]',
        '[class*="listItem"]',
    ].join(', ');

    const PRICE_RE = /\$\s*[\d,]+/;
    const STOCK_RE = /in\s+stock|in\s+total/i;

    const MAX_CLIMB = 8;

    /** The item id from an image path, or null if it is not an item image. */
    function itemIdFromImage(img) {
        if (!img || typeof img.getAttribute !== 'function') return null;

        const src = img.getAttribute('src') || img.getAttribute('srcset') || '';
        const match = src.match(ITEM_IMAGE_ID_RE);

        return match ? match[1] : null;
    }

    function isVisible(el) {
        if (!el || typeof window === 'undefined') return true;

        const style = window.getComputedStyle(el);
        if (style.display === 'none' || style.visibility === 'hidden') return false;

        const rect = el.getBoundingClientRect();
        return rect.width > 0 && rect.height > 0;
    }

    function boxOf(el) {
        if (!el || typeof el.getBoundingClientRect !== 'function') {
            return { width: 0, height: 0 };
        }
        return el.getBoundingClientRect();
    }

    function countItemImages(el) {
        try {
            return el.querySelectorAll(ITEM_IMAGE_SELECTOR).length;
        } catch {
            return 0;
        }
    }

    /**
     * Climb from an item image to the element representing ONE listing.
     *
     * The guard that matters: the moment an ancestor contains more than one item
     * image we have climbed into a container holding several listings and must
     * stop. Without it, one card's name gets paired with another card's price -
     * which is the oldest bug in this project.
     */
    function cardFromImage(img) {
        const preferred = img.closest ? img.closest(CARD_SELECTOR) : null;
        if (preferred && countItemImages(preferred) === 1) return preferred;

        let node = img.parentElement;
        let best = null;

        for (let depth = 0; depth < MAX_CLIMB && node; depth += 1) {
            if (countItemImages(node) > 1) break;

            best = node;

            const text = node.textContent || '';
            if (node.querySelector('[aria-label^="Buy"]') || PRICE_RE.test(text)) {
                return node;
            }

            node = node.parentElement;
        }

        return best;
    }

    /** Climb from a price-bearing element to something card-shaped. */
    function cardFromContent(el) {
        let node = el;

        for (let depth = 0; depth < MAX_CLIMB && node; depth += 1) {
            const text = node.textContent || '';
            const box = boxOf(node);

            if (
                PRICE_RE.test(text) &&
                STOCK_RE.test(text) &&
                node.querySelector('img') &&
                box.width >= 150 &&
                box.width <= 600 &&
                box.height >= 60 &&
                box.height <= 400
            ) {
                return node;
            }

            node = node.parentElement;
        }

        return null;
    }

    function dedupe(cards) {
        const seen = new Set();
        const out = [];

        for (const card of cards) {
            if (!card || seen.has(card)) continue;
            seen.add(card);
            out.push(card);
        }

        return out;
    }

    /** Strategy 1: anchored on item images. */
    function findByImage(root) {
        let images;
        try {
            images = Array.from(root.querySelectorAll(ITEM_IMAGE_SELECTOR));
        } catch {
            return { cards: [], images: 0 };
        }

        const cards = dedupe(images.map(cardFromImage).filter(Boolean));

        return { cards, images: images.length };
    }

    /** Strategy 2: shaped like a listing card. */
    function findByContent(root) {
        const candidates = [];

        let all;
        try {
            all = root.querySelectorAll('body *');
        } catch {
            return [];
        }

        for (const el of all) {
            const text = el.textContent || '';

            if (!text || text.length > 500) continue;
            if (!PRICE_RE.test(text)) continue;
            if (!STOCK_RE.test(text)) continue;
            if (!isVisible(el)) continue;

            const box = boxOf(el);
            if (box.width < 120 || box.height < 60) continue;

            candidates.push(el);
        }

        return dedupe(candidates.map(cardFromContent).filter(Boolean));
    }

    /**
     * Find every listing card on the page.
     *
     * @returns {{cards: Element[], strategy: string, images: number}}
     */
    function findCards(root) {
        if (!root) return { cards: [], strategy: 'none', images: 0 };

        const byImage = findByImage(root);
        if (byImage.cards.length > 0) {
            return {
                cards: byImage.cards,
                strategy: 'image',
                images: byImage.images,
            };
        }

        const byContent = findByContent(root);

        return {
            cards: byContent,
            strategy: byContent.length > 0 ? 'content' : 'none',
            images: byImage.images,
        };
    }

    /* ===== src/sources/dom/scan.js ===== */
    /*
     * Reading one listing card into numbers.
     *
     * Extraction order, most reliable first:
     *
     *   1. Torn's own buy-control ARIA label, which states everything outright:
     *        "Buy item Hammer, $100, 1 in total."
     *   2. The item image path, which carries the item id: /images/items/1/
     *   3. Text parsing, as a fallback: the first price, and "( N in stock)".
     *
     * Steps 1 and 2 were read off live Torn markup, so where they apply there is
     * no guessing at all. Step 3 exists because a layout that lacks both still
     * needs to work, and it is the approach already proven on live pages.
     */





    /** "Buy item Hammer, $100, 1 in total." */
    const BUY_LABEL_FULL_RE =
        /^buy item\s+(.+?),\s*\$([\d,]+(?:\.\d+)?),\s*([\d,]+)\s*in total/i;

    /** "Buy: Xanax" */
    const BUY_LABEL_NAME_RE = /^buy(?:\s+item)?:?\s+(.+?)\.?$/i;

    const BUY_CONTROL_SELECTOR =
        '[aria-label^="Buy item"], [aria-label^="Buy:"]';

    /** "( 5,931 in stock)" - a market-wide total, NOT stock at this price. */
    const IN_STOCK_RE = /\(?\s*([\d,]+)\s*in\s+stock/i;

    /** "1,805 available" - one seller's stock, which IS at this price. */
    const AVAILABLE_RE = /([\d,]+)\s*available/i;

    /** Every money figure in a block of text, in order. */
    const ALL_PRICES_RE = /\$\s*[\d,]+(?:\.\d+)?/g;

    /** Name cells, when the image alt is missing. */
    const NAME_SELECTOR = '[class*="name___"], [class*="itemName"], .name';

    /**
     * Parse Torn's buy-control ARIA label.
     * @returns {{name: string, price: number|null, qty: number|null}|null}
     */
    function parseBuyLabel(label) {
        if (typeof label !== 'string' || !label.trim()) return null;

        const text = label.trim();

        const full = text.match(BUY_LABEL_FULL_RE);
        if (full) {
            const price = parseMoney(full[2]);
            const qty = parseQuantity(full[3]);

            return {
                name: full[1].trim(),
                price: Number.isFinite(price) && price > 0 ? price : null,
                qty: Number.isFinite(qty) && qty > 0 ? qty : null,
            };
        }

        const bare = text.match(BUY_LABEL_NAME_RE);
        if (bare) return { name: bare[1].trim(), price: null, qty: null };

        return null;
    }

    function textOf(node) {
        if (!node) return '';
        return (node.textContent || '').trim();
    }

    /** The item name Torn shows on this card. */
    function nameFromCard(card) {
        const img = card.querySelector('img[alt]');
        const alt = img ? (img.getAttribute('alt') || '').trim() : '';
        if (alt) return alt;

        const named = card.querySelector(NAME_SELECTOR);
        const text = textOf(named);

        return text && text.length < 80 ? text : '';
    }

    /** Catalogue lookup: by id where possible, by name only as a fallback. */
    function resolveItem(card, index, buy) {
        const img = card.querySelector(ITEM_IMAGE_SELECTOR);
        const id = itemIdFromImage(img);

        if (id) {
            const byId = findItemById(index, id);
            if (byId) return byId;
        }

        const name = (buy && buy.name) || nameFromCard(card);
        return findItemByName(index, name);
    }

    /**
     * Read one card.
     * @returns {object|null}
     */
    function readCard(card, index, pageType) {
        const buyNode = card.querySelector(BUY_CONTROL_SELECTOR);
        const buy = buyNode
            ? parseBuyLabel(buyNode.getAttribute('aria-label'))
            : null;

        const item = resolveItem(card, index, buy);
        if (!item) return { skipped: 'noItem' };

        let marketTotal = null;

        const text = card.textContent || '';

        /*
         * Read LEAF elements, never the row's concatenated text.
         *
         * React emits no whitespace between sibling nodes, so a seller row's
         * textContent is "BCS605$6,9727 availableBUY". The price then parses as
         * $69,727 instead of $6,972 - wildly above any exit price, so the row is
         * judged unprofitable and never highlights, from a number that was never
         * on screen. Each leaf holds exactly one value, so reading leaves removes
         * the ambiguity instead of guessing at it.
         */
        const leaves = [];
        for (const node of card.querySelectorAll('*')) {
            if (node.children.length > 0) continue;
            const t = (node.textContent || '').trim();
            if (t) leaves.push(t);
        }

        const priceLeaf = leaves.find((t) => /^\$\s*[\d,]+(?:\.\d+)?$/.test(t));
        const qtyLeaf = leaves.find((t) => /^[\d,]+\s*available$/i.test(t));

        let price = buy && buy.price;
        let priceAssumed = false;

        if (!Number.isFinite(price) || price <= 0) {
            if (priceLeaf) {
                // A leaf that is nothing but a price is unambiguous.
                price = parseMoney(priceLeaf);
                priceAssumed = false;
            } else {
                /*
                 * No dedicated price cell. Reading from text is only a guess when
                 * there is more than one money figure to choose between; with
                 * exactly one, it is the price.
                 */
                const found = text.match(ALL_PRICES_RE) || [];

                price = found.length > 0 ? parseMoney(found[0]) : null;
                priceAssumed = found.length > 1;
            }
        }

        if (!Number.isFinite(price) || price <= 0) return { skipped: 'noPrice' };

        /*
         * Quantity, and crucially WHETHER IT IS AVAILABLE AT THIS PRICE.
         *
         * A category tile reports the market-wide total across every seller
         * ("694,057 in total", "5,931 in stock") while showing only the CHEAPEST
         * price. Multiplying the two is nonsense: of 694,057 Gasoline, only 1,805
         * are at $424 - the next seller wants $520. Doing that produced a
         * confident "+$3.58m" for a trade that does not exist.
         *
         * A seller row ("1,805 available") is the one case where the quantity
         * really is available at the stated price.
         */
        let qty = null;
        let qtyAtPrice = false;
        let qtyAssumed = false;

        if (qtyLeaf) {
            qty = parseQuantity(qtyLeaf);
            qtyAtPrice = Number.isFinite(qty) && qty > 0;
        } else {
            const available = text.match(AVAILABLE_RE);
            if (available) {
                qty = parseQuantity(available[1]);
                qtyAtPrice = Number.isFinite(qty) && qty > 0;
            }
        }

        if (!qtyAtPrice) {
            // Market-wide totals are context, never a multiplier.
            const total = buy && buy.qty ? buy.qty : null;
            const inStock = text.match(IN_STOCK_RE);

            marketTotal =
                total || (inStock ? parseQuantity(inStock[1]) : null) || null;

            qty = 1;
            qtyAssumed = true;
        }

        return {
            el: card,
            buyEl: buyNode || null,
            itemId: item.id,
            name: item.name,
            item,
            listingPrice: price,
            priceAssumed,
            qty,
            qtyAtPrice,
            qtyAssumed,
            marketTotal,
            source: pageType,
        };
    }

    /**
     * Read every listing on the current page.
     *
     * @param {string} pageType - from detectPage()
     * @param {Document|Element} root
     * @param {object} ctx
     * @param {object} ctx.index - item index from buildItemIndex()
     * @returns {{listings: Array, diagnostics: object}}
     */
    function scanDom(pageType, root, { index } = {}) {
        const diagnostics = {
            pageType,
            strategy: 'none',
            images: 0,
            cards: 0,
            fromAria: 0,
            noItem: 0,
            noPrice: 0,
            priceAssumed: 0,
            qtyAssumed: 0,
            listings: 0,
        };

        if (!root || !index) return { listings: [], diagnostics };

        const found = findCards(root);

        diagnostics.strategy = found.strategy;
        diagnostics.images = found.images;
        diagnostics.cards = found.cards.length;

        const listings = [];

        for (const card of found.cards) {
            const result = readCard(card, index, pageType);

            if (!result || result.skipped) {
                if (result && result.skipped === 'noItem') diagnostics.noItem += 1;
                if (result && result.skipped === 'noPrice') diagnostics.noPrice += 1;
                continue;
            }

            if (!result.priceAssumed && !result.qtyAssumed) {
                diagnostics.fromAria += 1;
            }
            if (result.priceAssumed) diagnostics.priceAssumed += 1;
            if (result.qtyAssumed) diagnostics.qtyAssumed += 1;

            listings.push(result);
        }

        diagnostics.listings = listings.length;

        return { listings, diagnostics };
    }

