#!/usr/bin/env node
/*
 * Zero-dependency bundler.
 *
 * The source is written as real ES modules so core/ and api/ can be unit
 * tested under node and later lifted into a web app unchanged. Tampermonkey
 * wants one file, so this walks the import graph from src/main.js, orders the
 * modules by dependency, strips the import/export syntax and concatenates
 * everything into a single IIFE behind a userscript header.
 *
 * Because concatenation flattens every module into one scope, the build
 * FAILS on a duplicate top-level name or an import of something that is not
 * exported. Those would otherwise be silent, confusing runtime bugs.
 *
 *     node build.mjs
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import vm from 'node:vm';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveImport, enginesCommit } from './tools/engines.mjs';
import { localGlobals } from './tools/local-globals.mjs';

const ROOT = dirname(fileURLToPath(import.meta.url));
const ENTRY = resolve(ROOT, 'src/main.js');
const OUT = resolve(ROOT, 'dist/torn-trading.user.js');

/*
 * Second copy at the repo root. Tampermonkey installs and auto-updates from a
 * raw URL, so the released script needs a stable path that does not move.
 */
const RELEASE_OUT = resolve(ROOT, 'torn-moneymaker.user.js');

const REPO_RAW =
    'https://raw.githubusercontent.com/abrahamdelosreyes17-oss/' +
    'torn-moneymaker-releases/main/torn-moneymaker.user.js';

/*
 * A test build (3.25.0: "we test with me using it ... only release on my command"):
 *     node build.mjs --test 3.25.0
 * writes dist/torn-trading.test.user.js and nothing else - not the released copy. Its version says
 * what it is and when it was built (the log and the zip carry it), and it has no update address:
 * Tampermonkey never swaps it for the released script, and nobody else's copy can turn into it.
 */
const TEST_AT = process.argv.indexOf('--test');
const TEST_OF = TEST_AT > 0 ? process.argv[TEST_AT + 1] : null;
if (TEST_AT > 0 && !/^[0-9]+[.][0-9]+[.][0-9]+$/.test(TEST_OF || '')) throw new Error('--test needs the version it is a test of: node build.mjs --test 3.25.0');
const TEST_OUT = resolve(ROOT, 'dist/torn-trading.test.user.js');
const stamp = (d) => [d.getFullYear(), d.getMonth() + 1, d.getDate()].map((n) => String(n).padStart(2, '0')).join('') + '.' + [d.getHours(), d.getMinutes()].map((n) => String(n).padStart(2, '0')).join('');

const VERSION = TEST_OF
    ? TEST_OF + '-test.' + stamp(new Date())
    : JSON.parse(await readFile(resolve(ROOT, 'package.json'), 'utf8')).version;

/*
 * The shared server's address is built in (3.25.0), so nobody types it: the SHARED_URL line of the
 * server's own .env on the laptop that builds (TORN_SERVER_ENV names another file). It is never
 * printed here. No file or no such line: a copy without Shared, which works alone.
 */
const SHARED_ENV = process.env.TORN_SERVER_ENV || 'D:/torn/server/.env';
let SHARED_HOME = '';
try {
    const line = /^SHARED_URL=(.*)$/m.exec(await readFile(SHARED_ENV, 'utf8'));
    const url = line ? new URL(line[1].trim().replace(/^["']|["']$/g, '')) : null;
    if (url && url.protocol === 'https:' && /^[a-z0-9-]+([.][a-z0-9-]+)*[.]workers[.]dev$/.test(url.hostname)) SHARED_HOME = url.origin;
} catch {
    // no server folder on this machine
}
const SHARED_HOST = SHARED_HOME ? new URL(SHARED_HOME).hostname : 'workers.dev';

const UPDATE_LINES = TEST_OF ? '' : ['// @downloadURL  ' + REPO_RAW, '// @updateURL    ' + REPO_RAW, ''].join(String.fromCharCode(10));

const HEADER = `// ==UserScript==
// @name         Torn Trading - Buyer-side Opportunity Scanner
// @namespace    torn-trading
// @version      ${VERSION}
// @description  Finds Bazaar and Item Market listings below NPC / market value - on the page you are viewing, and live from the Torn API and TornW3B - ranked by the profit you can actually realize.
// @author       -
// @match        https://www.torn.com/*
// @match        https://weav3r.dev/*
// @match        https://abrahamdelosreyes17-oss.github.io/torn-moneymaker-releases/traders.html*
// @run-at       document-idle
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_deleteValue
// @grant        GM_registerMenuCommand
// @grant        GM_openInTab
// @grant        GM_xmlhttpRequest
// @grant        GM_addValueChangeListener
// @connect      api.torn.com
// @connect      www.tornexchange.com
// @connect      weav3r.dev
// @connect      ${SHARED_HOST}
${UPDATE_LINES}// @noframes
// ==/UserScript==
// engines ${enginesCommit() || 'unknown'}

/*
 * Built from src/ by build.mjs - do not edit this file directly.
 *
 * Rules this script keeps, deliberately (see README.md):
 *   - Data comes from the Torn API or from the page you are currently
 *     viewing. It never requests a Torn page you are not on.
 *   - It never buys anything, and never presses Torn's buttons. Its buttons
 *     navigate (one page per press) or type one number into a Torn box on
 *     your press (Fill); you press Buy / Add / Accept yourself.
 *   - Public API key only; the key goes to api.torn.com and nowhere else,
 *     and is never logged.
 *   - The optional TornW3B bazaar feed (weav3r.dev) is opt-in, has its own
 *     client, and never receives the key.
 *   - The live feed runs in one visible tab only, and never raises alerts.
 *   - Shared needs no setting up and serves only the people its owner added.
 *     A copy with a Public key asks one server of ours (a workers.dev
 *     address) a few times a day whether this PC is one of them, with a word
 *     made from that key (a SHA-256 of it - not the key, which it cannot be
 *     turned back into). Only a PC the server knows then sends it player
 *     ids, item ids, prices and counts, and two marks for your friends: the
 *     bazaar listings you are going for and those you just bought - and that
 *     this is Torn Bids, with its version. Never a key, your name, your
 *     inventory or your cash.
 */
`;

const IMPORT_RE =
    /^[ \t]*import\s+(?:(\{[\s\S]*?\})|([A-Za-z0-9_$]+))\s+from\s+['"]([^'"]+)['"];?[ \t]*$/gm;
const BARE_IMPORT_RE = /^[ \t]*import\s+['"]([^'"]+)['"];?[ \t]*$/gm;
const EXPORT_RE = /^([ \t]*)export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)/gm;
const DECL_RE =
    /^(?:export\s+)?(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z0-9_$]+)/gm;

/** Parse one module: its dependencies, its imported names, its exports. */
function analyse(source, filePath) {
    const deps = [];
    const imports = [];

    for (const match of source.matchAll(IMPORT_RE)) {
        const [, braced, defaultName, spec] = match;

        if (defaultName) {
            throw new Error(
                `${filePath}: default imports are not supported by this bundler.`,
            );
        }

        const names = braced
            .replace(/[{}]/g, '')
            .split(',')
            .map((n) => n.trim())
            .filter(Boolean)
            .map((n) => {
                if (n.includes(' as ')) {
                    throw new Error(
                        `${filePath}: "import as" is not supported by this bundler.`,
                    );
                }
                return n;
            });

        deps.push(spec);
        imports.push({ spec, names });
    }

    for (const match of source.matchAll(BARE_IMPORT_RE)) {
        deps.push(match[1]);
    }

    const declared = new Set();
    for (const match of source.matchAll(DECL_RE)) {
        declared.add(match[1]);
    }

    return { deps, imports, declared };
}

function strip(source) {
    return source
        .replace(IMPORT_RE, '')
        .replace(BARE_IMPORT_RE, '')
        .replace(EXPORT_RE, '$1');
}

const modules = new Map();

async function load(filePath) {
    if (modules.has(filePath)) return modules.get(filePath);

    let source;
    try {
        source = await readFile(filePath, 'utf8');
    } catch {
        throw new Error(`Cannot read module: ${filePath}`);
    }

    const info = analyse(source, relative(ROOT, filePath));
    const record = { filePath, source, ...info, resolved: [] };
    modules.set(filePath, record);

    for (const spec of info.deps) {
        const depPath = resolveImport(filePath, spec);
        record.resolved.push(depPath);
        await load(depPath);
    }

    return record;
}

/** Depth-first post-order: a module is emitted after everything it needs. */
function order(entryPath) {
    const out = [];
    const state = new Map();

    function visit(filePath, stack) {
        const seen = state.get(filePath);
        if (seen === 'done') return;
        if (seen === 'visiting') {
            const cycle = [...stack, filePath]
                .map((p) => relative(ROOT, p))
                .join(' -> ');
            throw new Error(`Import cycle: ${cycle}`);
        }

        state.set(filePath, 'visiting');
        const record = modules.get(filePath);

        for (const dep of record.resolved) {
            visit(dep, [...stack, filePath]);
        }

        state.set(filePath, 'done');
        out.push(record);
    }

    visit(entryPath, []);
    return out;
}

function validate(ordered) {
    const owners = new Map();
    const problems = [];

    for (const record of ordered) {
        const where = relative(ROOT, record.filePath);

        for (const name of record.declared) {
            if (owners.has(name)) {
                problems.push(
                    `Duplicate top-level name "${name}" in ${where} ` +
                        `(already declared in ${owners.get(name)}). ` +
                        `Concatenation flattens scope, so names must be unique.`,
                );
            } else {
                owners.set(name, where);
            }
        }
    }

    for (const record of ordered) {
        const where = relative(ROOT, record.filePath);

        for (const { spec, names } of record.imports) {
            const depPath = resolveImport(record.filePath, spec);
            const dep = modules.get(depPath);

            for (const name of names) {
                if (!dep.declared.has(name)) {
                    problems.push(
                        `${where} imports "${name}" from ${spec}, ` +
                            `which does not declare it.`,
                    );
                }
            }
        }
    }

    if (problems.length) {
        throw new Error('Build failed:\n  - ' + problems.join('\n  - '));
    }
}

async function main() {
    await load(ENTRY);

    const ordered = order(ENTRY);
    validate(ordered);

    const body = ordered
        .map((record) => {
            const where = relative(ROOT, record.filePath).replace(/\\/g, '/');
            return `/* ===== ${where} ===== */\n` + strip(record.source).trim();
        })
        .join('\n\n');

    // 3.33.0 (tools/local-globals.mjs): String, Math, Map... looked up through Tampermonkey's sandbox once, at start.
    const declared = new Set(ordered.flatMap((record) => [...record.declared]));
    const local = localGlobals(body, declared);

    const bundle =
        HEADER +
        '\n(function (' + local.params + ') {\n' +
        "    'use strict';\n\n" +
        `    const TTV2_BUILD_VERSION = '${VERSION}';\n` +
        `    const TTV2_SHARED_HOME = '${SHARED_HOME}';\n\n` +
        indent(body) +
        '\n\n    boot();\n' +
        '})(' + local.args + ');\n';

    /*
     * Parse the bundle before writing it.
     *
     * v2.5.1 shipped a file that no browser could parse: a CSS comment inside
     * the styles template literal contained a backtick, which terminated the
     * string and broke the whole script. Tampermonkey silently ran nothing.
     * `node --check` caught it as a separate step and the failure was missed,
     * so the check belongs INSIDE the build where it cannot be skipped.
     */
    try {
        new vm.Script(bundle, { filename: 'torn-moneymaker.user.js' });
    } catch (error) {
        throw new Error(
            'Bundle is not valid JavaScript and was NOT written: ' +
                error.message,
        );
    }

    await mkdir(dirname(OUT), { recursive: true });
    if (TEST_OF) {
        await writeFile(TEST_OUT, bundle, 'utf8');
        console.log('Test build ' + VERSION + ': ' + relative(ROOT, TEST_OUT) + ' (no update address; the released copy is untouched).');
        return;
    }
    await writeFile(OUT, bundle, 'utf8');
    await writeFile(RELEASE_OUT, bundle, 'utf8');

    const kb = (Buffer.byteLength(bundle, 'utf8') / 1024).toFixed(1);
    console.log(
        `Built ${relative(ROOT, OUT)} from ${ordered.length} modules (${kb} KB).`,
    );
    console.log(SHARED_HOME ? 'Shared: the server address of this laptop is built in.' : 'Shared: no server address found (' + SHARED_ENV + '); this copy works alone.');
}

function indent(text) {
    return text
        .split('\n')
        .map((line) => (line.trim() ? '    ' + line : ''))
        .join('\n');
}

main().catch((error) => {
    console.error(error.message);
    process.exit(1);
});
